// Who may call what: server/router.access.md, a table generated from the access
// tag each procedure's builder sets (server/procedure-access.ts ACCESS). No resolver runs.
//
//   bun run access:table    rewrite the table from the router
//
// test/procedures.api.test.ts regenerates it in memory and fails on any difference
// (or an untagged procedure), so a permission change is always a visible diff.

import { readFileSync, writeFileSync } from 'node:fs'
import type { AnyRouter } from '@trpc/server'
import { z } from 'zod'
import { ACCESS, type Access } from '../server/procedure-access'

export const ACCESS_TABLE_FILE = new URL('../server/router.access.md', import.meta.url)

export type ProcedureInfo = {
  path: string
  kind: 'query' | 'mutation' | 'subscription'
  access: Access | null
}

const isAccess = (v: unknown): v is Access => typeof v === 'string' && Object.hasOwn(ACCESS, v)

function defOf(procedure: unknown): unknown {
  const holder =
    typeof procedure === 'function' || (typeof procedure === 'object' && procedure !== null)
  return holder && '_def' in procedure ? procedure._def : undefined
}

const defSchema = z.object({
  type: z.enum(['query', 'mutation', 'subscription']),
  meta: z.object({ access: z.custom<Access>(isAccess).optional() }).optional(),
})

/** Every procedure in `router`, by path, with its kind and tag (null = untagged). */
export function procedures(router: AnyRouter): ProcedureInfo[] {
  const flat: Record<string, unknown> = router._def.procedures
  return Object.entries(flat)
    .map(([path, procedure]) => {
      const parsed = defSchema.parse(defOf(procedure))
      return { path, kind: parsed.type, access: parsed.meta?.access ?? null }
    })
    .sort((a, b) => a.path.localeCompare(b.path))
}

const callers = Object.keys(Object.values(ACCESS)[0] ?? {})

/** The table's markdown. Throws, naming them, when a procedure has no tag. */
export function accessTable(router: AnyRouter): string {
  const all = procedures(router)
  const untagged = all.filter((p) => p.access === null).map((p) => p.path)
  if (untagged.length > 0) {
    throw new Error(
      `No access tag on: ${untagged.join(', ')}. Build every procedure from a tagged builder in server/trpc.ts (publicProcedure, protectedProcedure, adminProcedure), or give a new builder a tag in server/procedure-access.ts.`
    )
  }
  const yesNo = (allowed: boolean) => (allowed ? 'yes' : 'no')
  const rows = all.map((p) => {
    const row: Record<string, boolean> = p.access === null ? {} : ACCESS[p.access]
    return `| ${p.path} | ${p.kind} | ${callers.map((c) => yesNo(row[c] === true)).join(' | ')} |`
  })
  return [
    '# Who may call what',
    '',
    "Generated by `bun run access:table` from the access tag of each procedure's builder (`server/procedure-access.ts` `ACCESS`). Never edit it by hand: `test/procedures.api.test.ts` fails when it and the router disagree. When a row changes, say in the commit what permission changed and why.",
    '',
    'It covers the builder only. A rule inside a resolver ("only the author may edit") needs its own API test.',
    '',
    `| procedure | kind | ${callers.join(' | ')} |`,
    `| --- | --- | ${callers.map(() => '---').join(' | ')} |`,
    ...rows,
    '',
  ].join('\n')
}

export function committedAccessTable(): string | null {
  try {
    return readFileSync(ACCESS_TABLE_FILE, 'utf8')
  } catch {
    return null
  }
}

if (import.meta.main) {
  // The router's modules parse the environment on import; no database is touched.
  const { useTestEnv } = await import('./env')
  useTestEnv('postgres://access-table@localhost:1/none')
  const { appRouter } = await import('../server/router')
  writeFileSync(ACCESS_TABLE_FILE, accessTable(appRouter))
  console.log(`wrote server/router.access.md (${procedures(appRouter).length} procedures)`)
}
